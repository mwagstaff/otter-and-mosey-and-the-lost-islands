#!/usr/bin/env python3
"""Synthesises the game's placeholder sound effects and music loops from scratch.

Pure Python (no third-party packages); needs macOS `afconvert` to encode AAC.
Everything here is original and generated by this script, so there are no licences to track.
The files are intended as placeholders: drop replacement .m4a files with the same names into
OtterAndMosey/Resources/Audio to swap them.

Usage: python3 tools/synth_audio.py
"""
import math, pathlib, random, struct, subprocess, tempfile, wave

RATE = 22050
OUT = pathlib.Path(__file__).resolve().parent.parent / "OtterAndMosey/Resources/Audio"


def silence(seconds):
    return [0.0] * int(seconds * RATE)


def envelope(i, n, attack=0.005, release=0.08):
    t, total = i / RATE, n / RATE
    if t < attack:
        return t / attack
    if t > total - release:
        return max(0.0, (total - t) / release)
    return 1.0


def tone(freq, seconds, volume=1.0, shape="sine", decay=0.0, attack=0.005, release=0.05, freq_end=None, vibrato=0.0):
    n = int(seconds * RATE)
    out, phase = [], 0.0
    for i in range(n):
        f = freq if freq_end is None else freq + (freq_end - freq) * (i / n)
        if vibrato:
            f *= 1 + 0.03 * math.sin(2 * math.pi * vibrato * i / RATE)
        phase += 2 * math.pi * f / RATE
        if shape == "sine":
            s = math.sin(phase)
        elif shape == "bell":
            s = 0.6 * math.sin(phase) + 0.25 * math.sin(2 * phase) + 0.15 * math.sin(3.01 * phase)
        elif shape == "soft":
            s = 0.8 * math.sin(phase) + 0.2 * math.sin(2 * phase)
        else:  # triangle
            s = 2 / math.pi * math.asin(math.sin(phase))
        amp = envelope(i, n, attack, release) * (math.exp(-decay * i / RATE) if decay else 1.0)
        out.append(s * amp * volume)
    return out


def noise(seconds, volume=1.0, smooth=0.0, decay=0.0, attack=0.005, release=0.05, smooth_end=None, seed=1):
    rng = random.Random(seed)
    n = int(seconds * RATE)
    out, last = [], 0.0
    for i in range(n):
        k = smooth if smooth_end is None else smooth + (smooth_end - smooth) * (i / n)
        last = last * k + rng.uniform(-1, 1) * (1 - k)
        amp = envelope(i, n, attack, release) * (math.exp(-decay * i / RATE) if decay else 1.0)
        out.append(last * amp * volume)
    return out


def mix(*tracks):
    out = [0.0] * max(len(t) for t in tracks)
    for t in tracks:
        for i, s in enumerate(t):
            out[i] += s
    return out


def at(seconds, track):
    return silence(seconds) + track


def seq(*tracks):
    out = []
    for t in tracks:
        out += t
    return out


def note(name):
    names = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
    semitone = names[name[0]] + (1 if "#" in name else 0) + (-1 if "b" in name else 0)
    octave = int(name[-1])
    return 440.0 * 2 ** ((semitone - 9) / 12 + (octave - 4))


def arp(notes, step, length=0.3, shape="bell", decay=7, volume=0.6):
    return mix(*[at(i * step, tone(note(n), length, volume, shape, decay=decay)) for i, n in enumerate(notes)])


def write(name, samples, peak=0.7):
    top = max(1e-6, max(abs(s) for s in samples))
    data = b"".join(struct.pack("<h", int(max(-1, min(1, s / top * peak)) * 32767)) for s in samples)
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        with wave.open(tmp, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(data)
    subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "64000", tmp.name, str(OUT / f"{name}.m4a")], check=True)
    pathlib.Path(tmp.name).unlink()


