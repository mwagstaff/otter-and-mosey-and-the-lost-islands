def music(name, key, chords, bpm, seed, melody_octave=5, bars_per_chord=1, sparkle=True):
    """A gentle looping tune: bass, plucked chord arpeggios and a wandering pentatonic melody.
    Notes wrap round the end of the buffer so the loop is seamless."""
    rng = random.Random(seed)
    beat = 60 / bpm
    bar = beat * 4
    total = int(len(chords) * bars_per_chord * bar * RATE)
    out = [0.0] * total

    def add(start, samples):
        base = int(start * RATE)
        for i, s in enumerate(samples):
            out[(base + i) % total] += s

    scale = [note(n + str(melody_octave)) for n in key] + [note(key[0] + str(melody_octave + 1))]
    step = rng.randrange(len(scale))
    for index, chord in enumerate(chords):
        for rep in range(bars_per_chord):
            start = (index * bars_per_chord + rep) * bar
            add(start, tone(note(chord[0]) / 2, bar * 0.95, 0.34, "soft", decay=1.2, attack=0.02, release=0.3))
            pattern = [0, 1, 2, 1, 0, 2, 1, 2]
            for i, p in enumerate(pattern):
                add(start + i * beat / 2, tone(note(chord[p]), 0.5, 0.2, "bell", decay=6))
            for i in range(8):
                if rng.random() < (0.62 if i % 2 == 0 else 0.3):
                    step = max(0, min(len(scale) - 1, step + rng.choice([-2, -1, -1, 0, 1, 1, 2])))
                    length = beat * rng.choice([0.5, 0.5, 1, 1.5])
                    add(start + i * beat / 2, tone(scale[step], length + 0.25, 0.3, "soft", decay=3.5, attack=0.01, release=0.15))
            if sparkle and rep == bars_per_chord - 1 and rng.random() < 0.6:
                add(start + bar * 0.75, tone(note(chord[2]) * 2, 0.5, 0.1, "bell", decay=7))
    echo = int(beat * 0.75 * RATE)
    wet = [out[i] + 0.28 * out[(i - echo) % total] + 0.12 * out[(i - 2 * echo) % total] for i in range(total)]
    write(name, wet, 0.5)


